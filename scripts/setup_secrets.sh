#!/usr/bin/env bash
# One-time setup for the Docker stack. Creates (only if missing):
#   .env                                   API key, webhook token, Grafana password
#   monitoring/alertmanager/webhook_token  same webhook token, for Alertmanager
#   certs/server.crt + certs/server.key    self-signed TLS certificate for HTTPS
#   retrain_requests/, feedback/, mlflow_data/  folders mounted into containers
# None of these are committed to Git (see .gitignore).
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"

mkdir -p retrain_requests/processed feedback mlflow_data certs

if [ ! -f .env ]; then
  cat > .env <<ENV
# LogSentinel secrets - generated by scripts/setup_secrets.sh. Do NOT commit.
API_KEY=$(openssl rand -hex 16)
ALERT_WEBHOOK_TOKEN=$(openssl rand -hex 24)
GRAFANA_ADMIN_PASSWORD=$(openssl rand -hex 8)
ENV
  echo "Created .env"
else
  echo ".env already exists - keeping it"
fi

# Alertmanager reads the webhook token from a file.
grep '^ALERT_WEBHOOK_TOKEN=' .env | cut -d= -f2- | tr -d '\n' > monitoring/alertmanager/webhook_token
chmod 644 monitoring/alertmanager/webhook_token
echo "Wrote monitoring/alertmanager/webhook_token"

if [ ! -f certs/server.crt ]; then
  openssl req -x509 -nodes -newkey rsa:2048 -days 365 \
    -keyout certs/server.key -out certs/server.crt \
    -subj "/CN=localhost" -addext "subjectAltName=DNS:localhost,IP:127.0.0.1" 2>/dev/null
  chmod 644 certs/server.crt certs/server.key
  echo "Created self-signed certificate in certs/"
else
  echo "certs/server.crt already exists - keeping it"
fi

echo "Done. Your API key (also used by the web UI):"
grep '^API_KEY=' .env | cut -d= -f2-
